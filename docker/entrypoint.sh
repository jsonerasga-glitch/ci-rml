#!/bin/bash
# Prepares the database, then starts Apache.
#   1. waits until MySQL accepts connections
#   2. php spark migrate              -> creates any missing tables
#   3. php spark db:seed InitialDataSeeder -> loads data.sql only into an empty DB
set -e
# bash, not sh: dash drops environment variables whose names contain dots
# (database.default.hostname, app.baseURL), which CodeIgniter relies on.

cd /var/www/html

# PHP turns dots in environment variable names into underscores when it fills
# $_ENV/$_SERVER, and CodeIgniter 4.1 only looks for the dotted names. So copy
# the CodeIgniter settings from the container environment into .env, which
# CodeIgniter loads itself (dotted names intact).
{
  echo "# Generated by docker/entrypoint.sh from the container environment on every start."
  printenv | grep -E '^(CI_ENVIRONMENT|app\.|database\.|encryption\.|logger\.|cookie\.|session\.)[^=]*=' \
    | while IFS='=' read -r key value; do
        printf "%s = '%s'\n" "$key" "${value//\'/\\\'}"
      done
} > .env
chown www-data:www-data .env

echo "[entrypoint] waiting for the database ..."
i=0
until php -r 'mysqli_report(MYSQLI_REPORT_OFF); exit(@mysqli_connect(getenv("database.default.hostname"), getenv("database.default.username"), getenv("database.default.password"), getenv("database.default.database"), (int) getenv("database.default.port")) ? 0 : 1);'; do
  i=$((i + 1))
  if [ "$i" -ge 60 ]; then
    echo "[entrypoint] database not reachable after 120 s, giving up" >&2
    exit 1
  fi
  sleep 2
done

if [ "${RML_AUTO_MIGRATE:-1}" = "1" ]; then
  echo "[entrypoint] running migrations"
  php spark migrate
  echo "[entrypoint] seeding initial data (skipped when data already exists)"
  php spark db:seed InitialDataSeeder
fi

chown -R www-data:www-data writable

exec "$@"
