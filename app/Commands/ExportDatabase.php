<?php

namespace App\Commands;

use CodeIgniter\CLI\BaseCommand;
use CodeIgniter\CLI\CLI;

/**
 * Exports the current database into the files used by the baseline migration
 * and InitialDataSeeder, so the project can be moved to another machine:
 *
 *   app/Database/Data/schema.sql  – CREATE TABLE IF NOT EXISTS for every table
 *   app/Database/Data/data.sql    – INSERT statements for every row
 *
 * Usage:  php spark db:export
 *
 * Every statement is written on a single line ending with ";" so the loaders
 * can split the files line by line without a SQL parser.
 */
class ExportDatabase extends BaseCommand
{
	protected $group       = 'Database';
	protected $name        = 'db:export';
	protected $description = 'Export schema and data to app/Database/Data for moving the project to another machine.';

	/** Tables managed elsewhere: by CI itself or by their own migration. */
	public const SCHEMA_EXCLUDE = ['migrations', 'certificate_verifications', 'customer_accounts', 'calibration_requests', 'calibration_request_items'];
	public const DATA_EXCLUDE   = ['migrations'];

	private const ROWS_PER_INSERT = 50;

	public function run(array $params)
	{
		$db  = \Config\Database::connect();
		$dir = APPPATH . 'Database/Data/';
		if (! is_dir($dir)) {
			mkdir($dir, 0775, true);
		}

		$tables = $db->listTables();
		sort($tables);

		// ---------------------------------------------------------- schema
		$schema = "-- RML CMS schema, generated by `php spark db:export` on " . date('Y-m-d H:i:s') . "\n";
		foreach ($tables as $table) {
			if (in_array($table, self::SCHEMA_EXCLUDE, true)) {
				continue;
			}
			$row = $db->query('SHOW CREATE TABLE `' . $table . '`')->getRowArray();
			$schema .= $this->portableDdl($row['Create Table']) . ";\n";
		}
		file_put_contents($dir . 'schema.sql', $schema);

		// ------------------------------------------------------------ data
		$fh = fopen($dir . 'data.sql', 'wb');
		fwrite($fh, "-- RML CMS data, generated by `php spark db:export` on " . date('Y-m-d H:i:s') . "\n");
		$mysqli = $db->connID;
		$total  = 0;

		foreach ($tables as $table) {
			if (in_array($table, self::DATA_EXCLUDE, true)) {
				continue;
			}
			$result = $mysqli->query('SELECT * FROM `' . $table . '`', MYSQLI_USE_RESULT);
			$cols   = null;
			$batch  = [];
			$count  = 0;

			while ($r = $result->fetch_assoc()) {
				if ($cols === null) {
					$cols = '(`' . implode('`,`', array_keys($r)) . '`)';
				}
				$batch[] = '(' . implode(',', array_map(static function ($v) use ($mysqli) {
					// real_escape_string escapes \n and \r, so every statement stays on one line.
					return $v === null ? 'NULL' : "'" . $mysqli->real_escape_string($v) . "'";
				}, $r)) . ')';
				$count++;

				if (count($batch) === self::ROWS_PER_INSERT) {
					fwrite($fh, "INSERT INTO `{$table}` {$cols} VALUES " . implode(',', $batch) . ";\n");
					$batch = [];
				}
			}
			$result->free();
			if ($batch) {
				fwrite($fh, "INSERT INTO `{$table}` {$cols} VALUES " . implode(',', $batch) . ";\n");
			}
			$total += $count;
			CLI::write(str_pad($table, 45) . $count . ' rows');
		}
		fclose($fh);

		CLI::write('');
		CLI::write('Exported ' . count($tables) . " tables, {$total} rows to " . $dir, 'green');
	}

	/**
	 * Makes SHOW CREATE TABLE output re-runnable and portable:
	 * IF NOT EXISTS, no AUTO_INCREMENT counter, one line, and utf8mb4_unicode_ci
	 * instead of MySQL-8-only collations so it also loads on MariaDB / XAMPP.
	 */
	private function portableDdl(string $ddl): string
	{
		$ddl = preg_replace('/^CREATE TABLE /', 'CREATE TABLE IF NOT EXISTS ', $ddl);
		$ddl = preg_replace('/ AUTO_INCREMENT=\d+/', '', $ddl);
		$ddl = preg_replace('/ COLLATE[= ]\w+/', '', $ddl);
		$ddl = preg_replace('/ (?:DEFAULT )?CHARSET=\w+/', ' DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci', $ddl);
		$ddl = preg_replace('/ CHARACTER SET \w+/', '', $ddl);

		return preg_replace('/\s*\n\s*/', ' ', $ddl);
	}
}
